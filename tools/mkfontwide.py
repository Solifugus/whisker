#!/usr/bin/env python3
"""
The desktop's font beyond ASCII (design.md §5at): every character DejaVu Sans
Mono draws past ASCII, in the cell RV-9's console font uses -- 10x20, four
bits of coverage a pixel, the same face at the same size and baseline, found
the way RV-9's tools/mkfont.py finds them, so a line mixing ASCII and the
rest reads as one face.

Left out, each for a reason a cell cannot answer: combining marks (they draw
over the character before, and whisker counts every code point a column),
format and control characters, private use, and anything Unicode calls wide
(two columns -- design §5aj's width table). Past U+FFFF too: the table's
code points are 16 bits.

Box drawing and block elements are stretched to the cell's full height, so
lines drawn from them join from one row of text to the next as they join
across.

    python3 tools/mkfontwide.py > host/linux/font_wide.c
"""
import subprocess
import sys
import unicodedata
from fontTools import ttLib
from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H = 10, 20
STRIDE = (CELL_W + 1) // 2

path = subprocess.run(["fc-match", "-f", "%{file}", "DejaVu Sans Mono"],
                      capture_output=True, text=True).stdout.strip()
if not path or "DejaVuSansMono" not in path:
	sys.exit("DejaVu Sans Mono not found")

# RV-9's mkfont.py, unchanged: the largest size whose advance and line
# height both fit the cell, and the baseline centred in what is left.
best = None
for size in range(8, 26):
	f = ImageFont.truetype(path, size)
	ascent, descent = f.getmetrics()
	if f.getlength("M") <= CELL_W and (ascent + descent) <= CELL_H:
		best = (size, f, ascent)
	else:
		break
size, font, ascent = best
baseline = ascent + (CELL_H - ascent - font.getmetrics()[1]) // 2

LEFT_OUT = {"Mn", "Me", "Mc", "Cf", "Cc", "Co", "Cs", "Zl", "Zp"}
cmap = ttLib.TTFont(path).getBestCmap()
cps = [c for c in sorted(cmap) if 126 < c <= 0xFFFF
       and unicodedata.category(chr(c)) not in LEFT_OUT
       and unicodedata.east_asian_width(chr(c)) not in ("W", "F")]


def tall(c):
	"""box drawing and blocks: stretched from the em to the whole cell, so their
	strokes reach its top and bottom"""
	return 0x2500 <= c <= 0x259F


def glyph(c):
	if tall(c):
		# drawn four times over, across the font's own advance (9.6 pixels
		# at this size, not 10) and its own em (ascent + descent), then
		# box-filtered down to the whole cell -- or a line is lighter at
		# every seam between cells
		f4 = ImageFont.truetype(path, size * 4)
		a4, d4 = f4.getmetrics()
		img = Image.new("L", (round(f4.getlength("M")), a4 + d4), 0)
		ImageDraw.Draw(img).text((0, a4), chr(c), font=f4, fill=255, anchor="ls")
		img = img.resize((CELL_W, CELL_H), Image.BOX)
	else:
		img = Image.new("L", (CELL_W, CELL_H), 0)
		ImageDraw.Draw(img).text((0, baseline), chr(c), font=font, fill=255,
		                         anchor="ls")
	out = bytearray()
	for y in range(CELL_H):
		for x in range(0, CELL_W, 2):
			hi = img.getpixel((x, y)) >> 4
			lo = img.getpixel((x + 1, y)) >> 4 if x + 1 < CELL_W else 0
			out.append((hi << 4) | lo)
	return bytes(out)


print(f"""/*
 * The desktop's font beyond ASCII: {len(cps)} characters, {CELL_W}x{CELL_H} cells.
 *
 * Generated by whisker's tools/mkfontwide.py from {path.split("/")[-1]} at
 * {size}px -- RV-9's console font's face, size and baseline. Do not edit by
 * hand -- rerun the generator.
 *
 * rv9_font_wide_cp is sorted, for a binary search; glyph i is
 * rv9_font_wide[i], {CELL_H} rows of {STRIDE} bytes, two pixels a byte, four bits
 * of coverage each, high nibble leftmost -- font.c's layout.
 */
const unsigned short rv9_font_wide_n = {len(cps)};

const unsigned short rv9_font_wide_cp[{len(cps)}] = {{""")
for i in range(0, len(cps), 12):
	print("\t" + ",".join(f"0x{c:04x}" for c in cps[i:i + 12]) + ",")
print("};\n")
print(f"const unsigned char rv9_font_wide[{len(cps)}][{CELL_H * STRIDE}] = {{")
for c in cps:
	print(f"\t/* U+{c:04X} */ {{" + ",".join(str(b) for b in glyph(c)) + "},")
print("};")
print(f"font_wide: {len(cps)} glyphs at {size}px, {len(cps) * CELL_H * STRIDE} bytes",
      file=sys.stderr)
